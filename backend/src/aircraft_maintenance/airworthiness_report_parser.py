"""
Parser and Analyzer for Aircraft Maintenance & Airworthiness Status Reports.

Supports:
1. Excel / CSV workbooks with sheets or tables:
   - Aircraft_Profile
   - Inspection_AD_DueList
   - Maintenance_Defect_Log
2. Multi-page PDF airworthiness reports generated by Google AI or FAA SDR conventions:
   - Aircraft Identification & Powerplant Specifications
   - Inspection & Airworthiness Directive (AD) Due-List
   - Maintenance & Defect SDR Logbook
"""

